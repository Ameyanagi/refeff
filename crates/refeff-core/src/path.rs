//! FEFF path-finder packing helpers.
//!
//! `PATH/ipack.f90` stores up to eight path atom indices in three signed
//! integers by treating each packed field as base 1290. These helpers preserve
//! that representation for compatibility with FEFF path-degeneracy logic.
//! This module also ports the small companion-index min-heap maintenance
//! routines from `PATH/heap.f90`, the path distance/angle builder from
//! `PATH/mrb.f90`, and the path-pruning criteria from `PATH/mcrith.f90` and
//! `PATH/mcritk.f90`. Errors are structured instead of calling `par_stop`.

use ndarray::{Array2, ArrayView2, ArrayView3};
use thiserror::Error;

use crate::{
    Real,
    quadrature::{QuadratureError, strap},
    vector::single_precision_distance_between,
};

const PATH_PACK_BASE: i32 = 1_290;
const PATH_PACK_BASE_SQUARED: i32 = PATH_PACK_BASE * PATH_PACK_BASE;
const MAX_PACKED_PATH_INDICES: usize = 8;
const MAX_PACKED_PATH_VALUE: i32 = PATH_PACK_BASE - 1;
const DOT_COSINE_EPSILON: f32 = 1.0e-8;
const PATH_HASH_SCALE: f32 = 1_000.0;
const PATH_HASH_FACTOR: f32 = 16.123_457;
const PATH_HASH_POTENTIAL_FACTOR: f32 = 8.576_543;
const PATH_HASH_Y_WEIGHT: f32 = 0.894_375;
const PATH_HASH_Z_WEIGHT: f32 = 0.573_498;
const PATH_HASH_LENGTH_OFFSET: Real = 40_000_000.0;
const PATH_OUTPUT_MIN_ABS_ANGLE_COSINE: f32 = 0.3;
const PATH_STANDARD_EPSILON: Real = 1.0e-4;

/// Distances and angle cosines generated by FEFF `mrb`.
#[derive(Debug, Clone, PartialEq)]
pub struct PathGeometry {
    /// FEFF `ri`: leg lengths for each path point, including return to absorber.
    pub leg_distances: Vec<Real>,
    /// FEFF `beta`: cosines of scattering angles at each path point.
    pub angle_cosines: Vec<Real>,
    /// Sum of `leg_distances`, matching FEFF's local `rpath`.
    pub total_path_length: Real,
}

/// Result of FEFF `mcritk` output-importance calculation.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PathOutputCriterion {
    /// Output importance factor, or `None` for FEFF's undefined `xout = -1`.
    pub output_importance: Option<Real>,
    /// Updated `xcalcx` normalization. FEFF initializes it from `xcalc` when
    /// the input value is nonpositive.
    pub normalization: Real,
}

/// Inputs for FEFF `mcritk` output-importance calculation.
#[derive(Debug, Clone, Copy)]
pub struct PathOutputCriterionInput<'a> {
    /// FEFF `ipat(1:npat)`: path atom indices, with `0` as absorber.
    pub path_indices: &'a [usize],
    /// FEFF `ri(1:npat+1)`: path leg distances.
    pub leg_distances: &'a [Real],
    /// FEFF `beta(1:npat+1)`: path angle cosines.
    pub angle_cosines: &'a [Real],
    /// FEFF `indbet(1:npat+1)`: discretized beta bins for `fbetac`.
    pub beta_indices: &'a [i32],
    /// Atom-indexed FEFF potential IDs, equivalent to `ipot(atom)`.
    pub atom_potentials: &'a [usize],
    /// FEFF `fbetac(-nbeta:nbeta, 0:nph, necrit)` laid out as
    /// `(2 * nbeta + 1, nph + 1, necrit)`.
    pub fbeta_critical: ArrayView3<'a, Real>,
    /// FEFF `xlamc(1:nncrit)`: mean-free paths for criteria energies.
    pub mean_free_paths: &'a [Real],
    /// FEFF `ckspc(1:nncrit)`: wave numbers for criteria energies.
    pub wave_numbers: &'a [Real],
    /// FEFF `xcalcx`: normalization updated when nonpositive.
    pub current_normalization: Real,
}

